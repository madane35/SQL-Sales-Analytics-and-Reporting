# Magnitude Anlaysis

-- Find total customers by countries
select country,count(customer_key) as total_customers
from dim_customers
group by country
order by total_customers desc;

-- Find Total Customer By Gender
select gender,count(customer_key) as total_customers
from dim_customers
group by gender
order by total_customers desc;

-- Find Total Product By Category
select Category,count(product_key) as total_product 
from dim_products
group by category
order by total_product desc;

-- What Is The Average Costs In Each Category
select Category,avg(cost) as avg_cost
from dim_products
group by category
order by avg_cost desc;

-- What Is The Total Revenue Generated For Each Category
SELECT 
    d.category,SUM(f.sales_amount) AS total_revenue
FROM
    fact_sales f
        LEFT JOIN
    dim_products d ON f.product_key = d.product_key
GROUP BY d.category
ORDER BY total_revenue DESC;

-- What Is The Total Revenue Generated BY Each Customer
SELECT 
    customer_key, SUM(sales_amount) AS total_revenue
FROM
    fact_sales
group by   customer_key
order by total_revenue desc;

-- What Is The Distribution Of Sold Item Across Countries

SELECT 
    c.country, SUM(f.quantity) AS total_Sold_item
FROM
    fact_sales f
        LEFT JOIN
    dim_customers c ON c.customer_key = f.customer_key
GROUP BY c.country
ORDER BY total_sold_item DESC;


# Rank Analysis 
-- Which 5 Product Generate The Highest Revenue
SELECT  
    p.product_name,SUM(f.sales_amount) AS total_revenue
FROM
    fact_sales f
        LEFT JOIN
    dim_products p ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC
limit 5;

-- Which 5 Product Generate The Lowest Revenue
SELECT  
    p.product_name,SUM(f.sales_amount) AS total_revenue
FROM
    fact_sales f
        LEFT JOIN
    dim_products p ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue asc
limit 5;

-- Find Top 10 customers who have generated the highest revenue
SELECT 
    c.first_name,
    c.last_name,
    c.customer_key,
    SUM(f.sales_amount) AS total_revenue
FROM
    fact_sales f
        LEFT JOIN
    dim_customers c ON f.customer_key = c.customer_key
GROUP BY c.first_name , c.last_name , c.customer_key
ORDER BY total_revenue DESC
limit 10;

-- The 3 customers with the fewest orders palced
SELECT 
    c.first_name,
    c.last_name,
    c.customer_key,
  count(distinct f.order_number) as total_orders
FROM
    fact_sales f
        LEFT JOIN
    dim_customers c ON c.customer_key = f.customer_key
GROUP BY c.first_name , c.last_name , c.customer_key
ORDER BY  total_orders asc
limit 3;










